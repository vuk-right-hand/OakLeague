// section-segment.ts — pure-text segmentation for RAG v3 (book-scale ingest).
//
// The "Wall A" fix from RAG_SCALING_V3_PLAN.md §2.2: today's narrative-chunker
// sends the WHOLE document to Flash in one call (one of three pinned facts in
// the plan's §0 ground-truth). On a 200k-word book that blows the output
// ceiling and silently truncates. v3 inverts the flow — chunker LLM processes
// ONE SECTION per call — so this module's job is to cut the document into
// sections small enough that one Flash call always completes cleanly.
//
// Hard rules (plan §2.2):
//   1. NO LLM call. Segmentation is regex/heuristic + offsets. An LLM here
//      reintroduces the exact Wall-A-class input-size problem we're solving,
//      plus COGS, plus nondeterminism.
//   2. ZERO sections > safeMaxTokens in the output. Oversize source paragraphs
//      are sentence-split before packing; pathological single sentences are
//      hard-split as a last resort (counted in `oversize`).
//   3. Deterministic — same input produces byte-identical sections. This is
//      the prerequisite for per-section idempotent re-embed (audit C5: a crash
//      at section 200/400 of a book costs one section's re-pay, not the whole
//      book).
//   4. Char-offset contiguity (audit C2): section[i].charEnd === section[i+1].charStart,
//      sections[last].charEnd === text.length, sections[0].charStart === 0.
//      AND section.text === text.slice(section.charStart, section.charEnd) —
//      the audit-C5 resume path re-slices source by offsets to fingerprint a
//      section; this invariant is load-bearing.
//
// Title + summary are generated by the per-section Flash call downstream
// (`narrative-chunk.ts` will be extended for v3). This module returns only
// the structural cue line (heading text) as `cue` to bias that Flash call.
//
// Worker contract (out of scope for this module but caller MUST follow):
//   • For sample_content.type ∈ {book_or_doc, mastermind_or_course}, pass
//     cueMode: 'book' so transcript-style timestamp patterns don't false-fire
//     on log excerpts / sports times / UI mockups inside the book text.
//   • For type ∈ {youtube, transcript}, pass cueMode: 'transcript'.
//   • If a section's text (minus its cue line) is empty, the worker should
//     SKIP it — Flash will return zero narrative units on a heading-only
//     section. This module returns those sections honestly rather than
//     filtering, so the caller can choose its behavior.
//
// Pure, no I/O. server-only to keep it out of client bundles (it'll only ever
// run inside the embed-worker).

import 'server-only';

// ── Defaults (plan §2.2; safe-max tightened from 8000 → 7500 per audit small
//    for systemInstruction + responseSchema headroom inside the Flash call) ──
const DEFAULT_TARGET_TOKENS = 7000;
const DEFAULT_SAFE_MAX_TOKENS = 7500;
const DEFAULT_CHARS_PER_TOKEN = 4;

export type SegmentMode = 'structural' | 'paragraph-packed';
/** Cue-detection profile. Default 'auto' enables bracketed timestamps + bare
 *  timestamps (with blank-line guard) + headings + chapter + form-feed. 'book'
 *  suppresses timestamp patterns entirely (false-positive defense against
 *  `12:45 PM`, `09:15 INFO`, sports times in prose). 'transcript' is identical
 *  to 'auto' today but exists as an explicit caller intent. */
export type CueMode = 'auto' | 'book' | 'transcript';

export interface Section {
  /** Section text — EXACTLY equal to source.slice(charStart, charEnd) on the
   *  normalized input (CRLF→LF). This identity is the audit-C5 resume key. */
  text: string;
  /** Absolute char offset in the normalized input (CRLF→LF). Inclusive. */
  charStart: number;
  /** Absolute char offset in the normalized input. Exclusive of next section. */
  charEnd: number;
  /** Estimated tokens by `chars / charsPerToken` heuristic. Always ≤ safeMaxTokens. */
  estTokens: number;
  /** Trimmed structural cue line that started this section, or null for paragraph-packed. */
  cue: string | null;
  /** How this section was produced. Per-section, not per-document. */
  mode: SegmentMode;
}

export interface SegmentOptions {
  targetTokens?: number;
  safeMaxTokens?: number;
  /** chars-per-token heuristic. Default 4 (English Gemini). For CJK-heavy
   *  content the module auto-detects and drops to ~1.5 when this option is
   *  not provided. Explicit value always wins over auto-detect. */
  charsPerToken?: number;
  /** Cue-detection profile. Default 'auto'. */
  cueMode?: CueMode;
}

export interface SegmentResult {
  sections: Section[];
  /** Overall strategy that fired for this document. */
  mode: SegmentMode;
  /**
   * Count of source spans that had to be HARD-SPLIT (no sentence boundary
   * found inside a paragraph > safeMax). Telemetry signal — output is still
   * safe, but high oversize means upstream sanitization is letting through
   * unparseable content. Zero is the happy path.
   */
  oversize: number;
}

// ── Structural cue patterns (plan §2.2 — books / markdown / transcripts) ────
//
// INVARIANT: every pattern uses the `g` flag. `findCues()` resets `lastIndex
// = 0` before each scan and bumps it after zero-width matches; any future
// caller MUST do the same or the regex engine will skip / infinite-loop.
// These objects are module-level for allocation cost; they are NOT reentrant.
//
// Patterns are intentionally conservative on FALSE POSITIVES — shattering
// prose into orphan 1-token sections costs more than missing some real
// structure. Audit (round-4) findings:
//   • C1: form-feed line-anchored so mid-paragraph `\f` doesn't make the
//     whole merged line into a giant fake "cue title."
//   • M1: numbered-heading pattern added; ALL-CAPS deferred to v3.1 (the
//     false-positive surface — "FAQ", "USA", "OK" in prose — needs a
//     larger design pass).
//   • M2/M3: bare timestamps + numbered headings are blank-line-guarded
//     in findCues to suppress in-prose false positives.

// Patterns that fire under EVERY cueMode.
const CUE_PATTERNS_ALWAYS: ReadonlyArray<RegExp> = [
  // Markdown headings: 1–6 `#`, at least one space, then content.
  /^#{1,6} +\S.*$/gm,
  // Form-feed at line start (book page-break artifact).
  /^[ \t]*\f.*$/gm,
  // "Chapter N" / "CHAPTER N" — exact line-start, case-insensitive.
  /^chapter\s+\d+\b.*$/gim,
  // Numbered top-level headings: "1. Introduction" / "12. Methods" with a
  // capitalized title following. Blank-line-guarded in findCues so "1. first
  // reason" inside a prose list doesn't shatter.
  /^\d{1,3}\.\s+[A-Z]\S.*$/gm,
];

// Patterns suppressed under cueMode='book' (high false-positive risk inside
// book/doc sample types — `09:15 INFO`, `12:45 PM`, sports times).
const CUE_PATTERNS_TIMESTAMP: ReadonlyArray<RegExp> = [
  // Bracketed timestamps `[00:05:30]` — high precision, fires always.
  /^\[\d{1,2}:\d{2}(?::\d{2})?\](?=[ \t]|$).*$/gm,
  // Bare `MM:SS` / `HH:MM:SS` — blank-line-guarded in findCues.
  /^\d{1,2}:\d{2}(?::\d{2})?(?=[ \t]|$).*$/gm,
];

interface CuePosition {
  start: number;   // absolute line-start offset
  cueLine: string; // trimmed line text
}

function isBareTimestampCue(cueLine: string): boolean {
  return /^\d{1,2}:\d{2}/.test(cueLine);
}

function isNumberedHeadingCue(cueLine: string): boolean {
  return /^\d{1,3}\.\s+[A-Z]/.test(cueLine);
}

/** True if `pos` in `text` is at start-of-document, or preceded by at least
 *  one blank line (zero or more spaces/tabs between two newlines). */
function hasBlankLineBefore(text: string, pos: number): boolean {
  if (pos === 0) return true;
  let i = pos - 1;
  // Skip the newline that ends the cue's own preceding line.
  if (i >= 0 && text[i] === '\n') i--;
  // Skip horizontal whitespace on that line.
  while (i >= 0 && (text[i] === ' ' || text[i] === '\t')) i--;
  if (i < 0) return true;
  // That line is blank only if its content collapsed to nothing AND it's
  // terminated by another newline (or start-of-doc).
  return text[i] === '\n';
}

/** True if the line starting at `lineStart` in `text` is followed by a blank
 *  line (or EOF). Walks: end of cue line, skip horizontal whitespace, expect
 *  `\n` (or EOF). Used to kill numbered-list false positives where item #1
 *  happens to have blank-above but is followed immediately by item #2. */
function hasBlankLineAfter(text: string, lineStart: number): boolean {
  const lineEnd = text.indexOf('\n', lineStart);
  if (lineEnd === -1) return true;
  let i = lineEnd + 1;
  while (i < text.length && (text[i] === ' ' || text[i] === '\t')) i++;
  if (i >= text.length) return true;
  return text[i] === '\n';
}

function findCues(text: string, cueMode: CueMode): CuePosition[] {
  const patterns: RegExp[] = [...CUE_PATTERNS_ALWAYS];
  if (cueMode !== 'book') patterns.push(...CUE_PATTERNS_TIMESTAMP);

  const found: CuePosition[] = [];
  for (const re of patterns) {
    re.lastIndex = 0;
    let m: RegExpExecArray | null;
    while ((m = re.exec(text)) !== null) {
      const matchIdx = m.index;
      const lineStart = text.lastIndexOf('\n', matchIdx - 1) + 1;
      const lineEndRaw = text.indexOf('\n', matchIdx);
      const lineEnd = lineEndRaw === -1 ? text.length : lineEndRaw;
      const cueLine = text.slice(lineStart, lineEnd).trim();
      if (cueLine.length > 0) {
        found.push({ start: lineStart, cueLine });
      }
      // Defensive: zero-length matches (none today, but defend against future
      // pattern edits) would infinite-loop in re.exec.
      if (re.lastIndex === matchIdx) re.lastIndex = matchIdx + 1;
    }
  }
  // Dedup by position (same line may match multiple patterns) and sort.
  found.sort((a, b) => a.start - b.start);
  const deduped: CuePosition[] = [];
  for (const c of found) {
    if (deduped.length === 0 || deduped[deduped.length - 1].start !== c.start) {
      deduped.push(c);
    }
  }
  // Context guards (false-positive defenses, audit-driven):
  //   • Bare timestamps + numbered headings need a blank line ABOVE (suppresses
  //     in-prose mid-paragraph mismatch).
  //   • Numbered headings ALSO need a blank line BELOW (suppresses mid-list
  //     shatter where item #1 happens to follow a paragraph end but items #2+
  //     are consecutive — observed on real creator content, AoD module 04
  //     lines 686-689: prose enumeration where item #1 had blank-above).
  return deduped.filter((c) => {
    const numbered = isNumberedHeadingCue(c.cueLine);
    const bareTime = isBareTimestampCue(c.cueLine);
    if (!numbered && !bareTime) return true;
    if (c.start !== 0 && !hasBlankLineBefore(text, c.start)) return false;
    if (numbered && !hasBlankLineAfter(text, c.start)) return false;
    return true;
  });
}

// ── CJK auto-detect (audit C4) ──────────────────────────────────────────────
//
// Default chars/token=4 is calibrated for English. Gemini's BPE tokenizes CJK
// at ~1–2 chars/token; a Mandarin or Japanese transcript estimated at chars/4
// silently overruns Flash budgets and breaks the "ZERO sections > safeMax"
// hard rule for any non-Latin creator content. Sample up to 4KB of the doc;
// if >10% lands in CJK Unicode ranges, drop to chars/1.5. The CALLER's
// explicit `charsPerToken` always wins — auto-detect runs only when the
// option is unset (checked at the call site, not here).
function detectCharsPerToken(text: string): number {
  const sample = text.length > 4096 ? text.slice(0, 4096) : text;
  if (sample.length === 0) return DEFAULT_CHARS_PER_TOKEN;
  let cjk = 0;
  for (let i = 0; i < sample.length; i++) {
    const c = sample.charCodeAt(i);
    if (
      (c >= 0x4e00 && c <= 0x9fff) ||   // CJK Unified Ideographs
      (c >= 0x3040 && c <= 0x30ff) ||   // Hiragana + Katakana
      (c >= 0xac00 && c <= 0xd7af)      // Hangul Syllables
    ) cjk++;
  }
  return cjk / sample.length > 0.1 ? 1.5 : DEFAULT_CHARS_PER_TOKEN;
}

// ── Paragraph parsing ───────────────────────────────────────────────────────
//
// Paragraphs are blank-line-separated. We track each paragraph's absolute char
// offsets in the source so the packer can produce contiguous section spans.

interface Paragraph {
  text: string;
  charStart: number;
  charEnd: number;
  estTokens: number;
}

function estimateTokens(text: string, charsPerToken: number): number {
  if (text.length === 0) return 0;
  return Math.ceil(text.length / charsPerToken);
}

function parseParagraphs(
  text: string,
  baseOffset: number,
  charsPerToken: number,
): Paragraph[] {
  const out: Paragraph[] = [];
  const re = /\n[ \t]*\n+/g;
  let cursor = 0;
  let m: RegExpExecArray | null;
  while ((m = re.exec(text)) !== null) {
    const para = text.slice(cursor, m.index);
    if (para.trim().length > 0) {
      out.push({
        text: para,
        charStart: baseOffset + cursor,
        charEnd: baseOffset + m.index,
        estTokens: estimateTokens(para, charsPerToken),
      });
    }
    cursor = m.index + m[0].length;
  }
  if (cursor < text.length) {
    const tail = text.slice(cursor);
    if (tail.trim().length > 0) {
      out.push({
        text: tail,
        charStart: baseOffset + cursor,
        charEnd: baseOffset + text.length,
        estTokens: estimateTokens(tail, charsPerToken),
      });
    }
  }
  return out;
}

// ── Oversize handling: sentence-split, then hard-split as last resort ──────
//
// Sentence terminator (audit C3 + small): Latin `[.!?]` followed by optional
// closing quote/paren/bracket then whitespace, OR a CJK terminator `[。！？]`
// (which usually has no following whitespace). Dialog-heavy prose ending
// sentences with `." `, `?" `, `!" ` would otherwise miss EVERY boundary and
// fall through to hard-char-splits.

interface SplitUnit extends Paragraph {
  /** True if this unit came from a hard char-split (no sentence boundary
   *  available). Tallied into SegmentResult.oversize. */
  hardSplit: boolean;
}

function sentenceSplit(p: Paragraph, charsPerToken: number, safeMax: number): SplitUnit[] {
  const re = /(?:[.!?]+["')\]]*\s+)|(?:[。！？]+)/g;
  const boundaries: number[] = [];
  let m: RegExpExecArray | null;
  while ((m = re.exec(p.text)) !== null) {
    const end = m.index + m[0].length;
    if (end === m.index) {
      re.lastIndex = m.index + 1;   // zero-width defense
      continue;
    }
    boundaries.push(end);
  }
  if (boundaries.length === 0) {
    return hardSplit(p, charsPerToken, safeMax);
  }
  const sentences: SplitUnit[] = [];
  let prev = 0;
  const cuts = boundaries[boundaries.length - 1] === p.text.length
    ? boundaries
    : [...boundaries, p.text.length];
  for (const b of cuts) {
    if (b <= prev) continue;
    const txt = p.text.slice(prev, b);
    if (txt.trim().length === 0) {
      prev = b;
      continue;
    }
    const tok = estimateTokens(txt, charsPerToken);
    const unit: SplitUnit = {
      text: txt,
      charStart: p.charStart + prev,
      charEnd: p.charStart + b,
      estTokens: tok,
      hardSplit: false,
    };
    if (tok > safeMax) {
      sentences.push(...hardSplit(unit, charsPerToken, safeMax));
    } else {
      sentences.push(unit);
    }
    prev = b;
  }
  if (sentences.length === 0) {
    // M7 — pathological whitespace-only paragraph slipped through. Emit a
    // single hard-split unit covering the full range so the char chain stays
    // contiguous and the oversize counter ticks honestly.
    return [{ ...p, hardSplit: true }];
  }
  return sentences;
}

function hardSplit(p: Paragraph, charsPerToken: number, safeMax: number): SplitUnit[] {
  const maxChars = Math.max(1, safeMax * charsPerToken);
  const out: SplitUnit[] = [];
  for (let i = 0; i < p.text.length; i += maxChars) {
    const slice = p.text.slice(i, i + maxChars);
    if (slice.trim().length === 0) continue;
    out.push({
      text: slice,
      charStart: p.charStart + i,
      charEnd: p.charStart + Math.min(i + maxChars, p.text.length),
      estTokens: estimateTokens(slice, charsPerToken),
      hardSplit: true,
    });
  }
  if (out.length === 0) {
    // M7 — input was whitespace-only; preserve the range as a single unit.
    return [{ ...p, hardSplit: true }];
  }
  return out;
}

// ── Greedy packing — the rule that doesn't shatter prose into orphans ──────
//
// Flush rule: keep growing the current section until EITHER
//   (a) adding the next unit would exceed safeMaxTokens (hard ceiling), OR
//   (b) the current section already reaches targetTokens (soft target).
// Tiny units (≪ target) get fused with whatever comes next instead of
// becoming orphan sections. This is the rule that makes a 3-token "Chapter 1"
// heading ride along with its first body paragraph rather than emitting a
// 3-token section that downstream Flash returns zero narrative units for.

interface PackBucket {
  charStart: number;
  charEnd: number;
  estTokens: number;
}

function greedyPack(
  units: SplitUnit[],
  targetTokens: number,
  safeMaxTokens: number,
): { buckets: PackBucket[]; oversize: number } {
  const buckets: PackBucket[] = [];
  let oversize = 0;
  let cur: PackBucket | null = null;
  for (const u of units) {
    if (u.hardSplit) oversize++;
    if (cur === null) {
      cur = { charStart: u.charStart, charEnd: u.charEnd, estTokens: u.estTokens };
      continue;
    }
    const wouldOverflow = cur.estTokens + u.estTokens > safeMaxTokens;
    const atTarget = cur.estTokens >= targetTokens;
    if (wouldOverflow || atTarget) {
      buckets.push(cur);
      cur = { charStart: u.charStart, charEnd: u.charEnd, estTokens: u.estTokens };
    } else {
      cur.charEnd = u.charEnd;
      cur.estTokens += u.estTokens;
    }
  }
  if (cur !== null) buckets.push(cur);
  return { buckets, oversize };
}

function packParagraphs(
  paragraphs: Paragraph[],
  targetTokens: number,
  safeMaxTokens: number,
  charsPerToken: number,
): { buckets: PackBucket[]; oversize: number } {
  const units: SplitUnit[] = [];
  for (const p of paragraphs) {
    if (p.estTokens <= safeMaxTokens) {
      units.push({ ...p, hardSplit: false });
    } else {
      units.push(...sentenceSplit(p, charsPerToken, safeMaxTokens));
    }
  }
  return greedyPack(units, targetTokens, safeMaxTokens);
}

// ── Section assembly — buckets → Section objects with contiguous offsets ──
//
// After stretching each section's charEnd to the next section's charStart,
// the section's text field is RE-SLICED from the source (audit C2) so that
// section.text === source.slice(section.charStart, section.charEnd). This is
// the load-bearing invariant for audit-C5 resume fingerprinting.

function bucketsToSections(
  buckets: PackBucket[],
  /** First section's charStart — coerced to a fixed value (usually 0 or the
   *  containing region start) so leading whitespace isn't orphaned. */
  regionStart: number,
  /** Last section's charEnd — coerced so trailing whitespace is owned. */
  regionEnd: number,
  inheritedCue: string | null,
  mode: SegmentMode,
  source: string,
  charsPerToken: number,
): Section[] {
  if (buckets.length === 0) return [];
  const sections: Section[] = buckets.map((b) => ({
    text: '',                  // re-sliced below
    charStart: b.charStart,
    charEnd: b.charEnd,
    estTokens: b.estTokens,    // recomputed below
    cue: inheritedCue,
    mode,
  }));
  sections[0].charStart = regionStart;
  for (let i = 0; i < sections.length - 1; i++) {
    sections[i].charEnd = sections[i + 1].charStart;
  }
  sections[sections.length - 1].charEnd = regionEnd;
  for (const s of sections) {
    s.text = source.slice(s.charStart, s.charEnd);
    s.estTokens = estimateTokens(s.text, charsPerToken);
  }
  return sections;
}

// ── Structural mode: split at cues, sub-pack any oversize chapter ──────────

function structuralSections(
  text: string,
  cues: CuePosition[],
  targetTokens: number,
  safeMaxTokens: number,
  charsPerToken: number,
): { sections: Section[]; oversize: number } {
  // Build region boundaries. If there's body content before the first cue,
  // it becomes a cue-less leading section. If there's ONLY whitespace before,
  // the first cue's region extends back to 0 so no chars are orphaned (M5).
  const boundaries: { start: number; cueLine: string | null }[] = [];
  const firstCueStart = cues[0]!.start;
  if (firstCueStart > 0) {
    const leadingNonEmpty = text.slice(0, firstCueStart).trim().length > 0;
    if (leadingNonEmpty) {
      boundaries.push({ start: 0, cueLine: null });
      for (const c of cues) boundaries.push({ start: c.start, cueLine: c.cueLine });
    } else {
      boundaries.push({ start: 0, cueLine: cues[0]!.cueLine });
      for (let i = 1; i < cues.length; i++) {
        boundaries.push({ start: cues[i]!.start, cueLine: cues[i]!.cueLine });
      }
    }
  } else {
    for (const c of cues) boundaries.push({ start: c.start, cueLine: c.cueLine });
  }

  const sections: Section[] = [];
  let totalOversize = 0;
  for (let i = 0; i < boundaries.length; i++) {
    const start = boundaries[i].start;
    const end = i + 1 < boundaries.length ? boundaries[i + 1].start : text.length;
    const cueLine = boundaries[i].cueLine;
    const regionText = text.slice(start, end);
    const regionTokens = estimateTokens(regionText, charsPerToken);
    if (regionTokens <= safeMaxTokens) {
      sections.push({
        text: regionText,
        charStart: start,
        charEnd: end,
        estTokens: regionTokens,
        cue: cueLine,
        mode: 'structural',
      });
      continue;
    }
    // Oversize chapter — sub-pack at paragraph boundaries.
    const paragraphs = parseParagraphs(regionText, start, charsPerToken);
    const { buckets, oversize } = packParagraphs(
      paragraphs,
      targetTokens,
      safeMaxTokens,
      charsPerToken,
    );
    totalOversize += oversize;
    sections.push(...bucketsToSections(
      buckets,
      start,
      end,
      cueLine,
      'structural',
      text,
      charsPerToken,
    ));
  }
  return { sections, oversize: totalOversize };
}

// ── Public entry point ─────────────────────────────────────────────────────

export function segmentDocument(
  rawText: string,
  opts: SegmentOptions = {},
): SegmentResult {
  const targetTokens = opts.targetTokens ?? DEFAULT_TARGET_TOKENS;
  const safeMaxTokens = opts.safeMaxTokens ?? DEFAULT_SAFE_MAX_TOKENS;
  const cueMode: CueMode = opts.cueMode ?? 'auto';

  // Normalize CRLF→LF. We do NOT collapse other whitespace — char offsets
  // must remain interpretable as 1:1 indices into the normalized string.
  const text = rawText.replace(/\r\n/g, '\n');

  if (text.trim().length === 0) {
    return { sections: [], mode: 'paragraph-packed', oversize: 0 };
  }

  // CJK auto-detection (audit C4): runs only when the caller did NOT pass
  // an explicit charsPerToken — `undefined` check, NOT "equals default", so
  // a caller explicitly forcing `charsPerToken: 4` defeats the heuristic.
  const charsPerToken =
    opts.charsPerToken !== undefined ? opts.charsPerToken : detectCharsPerToken(text);

  const cues = findCues(text, cueMode);
  if (cues.length > 0) {
    const { sections, oversize } = structuralSections(
      text,
      cues,
      targetTokens,
      safeMaxTokens,
      charsPerToken,
    );
    return { sections, mode: 'structural', oversize };
  }

  // No structural cues — paragraph-pack mode.
  const paragraphs = parseParagraphs(text, 0, charsPerToken);
  const { buckets, oversize } = packParagraphs(
    paragraphs,
    targetTokens,
    safeMaxTokens,
    charsPerToken,
  );
  const sections = bucketsToSections(
    buckets,
    0,
    text.length,
    null,
    'paragraph-packed',
    text,
    charsPerToken,
  );
  return { sections, mode: 'paragraph-packed', oversize };
}
